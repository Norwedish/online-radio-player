/**
 * Icecast configuration generator (PLAN §6.5.3 / M5.3 / M13.4). Produces an
 * icecast.xml for the configured mounts: localhost bind, source/admin auth from
 * secrets, per-mount metadata, CORS header for the web player, a `/live`
 * ingest mount for external DJs (ADR 0004) and fallback mounts so a dead
 * mobile/opus mount falls back to the primary.
 */
import type { StationConfig } from "./config.js";

export interface IcecastSecrets {
  sourcePassword: string;
  adminPassword: string;
  relayPassword?: string;
  livePassword?: string;
}

export interface IcecastPaths {
  basedir: string;
  logdir: string;
  webroot: string;
  adminroot: string;
  pidfile?: string;
}

export interface IcecastRenderOptions {
  hostname?: string;
  location?: string;
  adminEmail?: string;
  clients?: number;
  /** Only valid when Icecast starts as root (it then drops privileges). */
  changeOwner?: { user: string; group: string };
  corsOrigin?: string;
}

function esc(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function renderIcecastXml(
  config: Pick<StationConfig, "station" | "icecast">,
  secrets: IcecastSecrets,
  paths: IcecastPaths,
  options: IcecastRenderOptions = {},
): string {
  const primary = config.icecast.mounts.find((m) => m.primary) ?? config.icecast.mounts[0]!;
  const mounts = config.icecast.mounts
    .map(
      (m) => `  <mount type="normal">
    <mount-name>/${esc(m.name)}</mount-name>
    <public>${m.public ? 1 : 0}</public>
    <charset>UTF-8</charset>
    <stream-name>${esc(config.station.name)}${m.primary ? "" : ` (${esc(m.bitrate)})`}</stream-name>
    <stream-description>${esc(config.station.name)} ${esc(m.codec.toUpperCase())} ${esc(m.bitrate)}</stream-description>
    <type>${esc(m.contentType)}</type>
    <bitrate>${parseInt(m.bitrate, 10)}</bitrate>${
      !m.primary && m.codec === primary.codec
        ? `\n    <fallback-mount>/${esc(primary.name)}</fallback-mount>\n    <fallback-override>1</fallback-override>`
        : ""
    }
    <http-headers>
      <header name="Access-Control-Allow-Origin" value="${esc(options.corsOrigin ?? "*")}" />
      <header name="Cache-Control" value="no-cache, no-store" />
    </http-headers>
  </mount>`,
    )
    .join("\n");
  const live = `  <mount type="normal">
    <mount-name>${esc(config.icecast.liveMount)}</mount-name>
    <username>source</username>
    <password>${esc(secrets.livePassword ?? secrets.sourcePassword)}</password>
    <public>0</public>
    <hidden>1</hidden>
    <max-listeners>2</max-listeners>
  </mount>`;
  const owner = options.changeOwner
    ? `
  <security>
    <chroot>0</chroot>
    <changeowner>
      <user>${esc(options.changeOwner.user)}</user>
      <group>${esc(options.changeOwner.group)}</group>
    </changeowner>
  </security>`
    : "";
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by online-radio-player (pnpm icecast:config). Do not edit by hand. -->
<icecast>
  <location>${esc(options.location ?? config.station.name)}</location>
  <admin>${esc(options.adminEmail ?? `admin@${config.station.domain}`)}</admin>
  <hostname>${esc(options.hostname ?? config.station.domain)}</hostname>

  <limits>
    <clients>${options.clients ?? 2000}</clients>
    <sources>${config.icecast.mounts.length + 2}</sources>
    <queue-size>524288</queue-size>
    <client-timeout>30</client-timeout>
    <header-timeout>15</header-timeout>
    <source-timeout>10</source-timeout>
    <burst-on-connect>1</burst-on-connect>
    <burst-size>65535</burst-size>
  </limits>

  <authentication>
    <source-password>${esc(secrets.sourcePassword)}</source-password>
    <relay-password>${esc(secrets.relayPassword ?? secrets.sourcePassword)}</relay-password>
    <admin-user>${esc(config.icecast.adminUser)}</admin-user>
    <admin-password>${esc(secrets.adminPassword)}</admin-password>
  </authentication>

  <listen-socket>
    <port>${config.icecast.port}</port>
    <bind-address>${esc(config.icecast.host)}</bind-address>
  </listen-socket>

${mounts}
${live}

  <fileserve>1</fileserve>
  <paths>
    <basedir>${esc(paths.basedir)}</basedir>
    <logdir>${esc(paths.logdir)}</logdir>
    <webroot>${esc(paths.webroot)}</webroot>
    <adminroot>${esc(paths.adminroot)}</adminroot>${paths.pidfile ? `\n    <pidfile>${esc(paths.pidfile)}</pidfile>` : ""}
    <alias source="/" destination="/status.xsl"/>
  </paths>

  <logging>
    <accesslog>access.log</accesslog>
    <errorlog>error.log</errorlog>
    <loglevel>3</loglevel>
    <logsize>10000</logsize>
    <logarchive>1</logarchive>
  </logging>${owner}
</icecast>
`;
}

/** Parses Icecast `status-json.xsl` into per-mount listener counts. */
export function parseIcecastStatus(
  json: unknown,
): { mount: string; listeners: number; contentType: string | null; title: string | null }[] {
  const stats = (json as { icestats?: { source?: unknown } })?.icestats;
  const raw = stats?.source;
  const sources = Array.isArray(raw) ? raw : raw ? [raw] : [];
  return sources.map((s: Record<string, unknown>) => {
    const url = String(s.listenurl ?? "");
    const mount = url.replace(/^https?:\/\/[^/]+\//, "");
    return {
      mount,
      listeners: Number(s.listeners ?? 0),
      contentType: (s.server_type as string | undefined) ?? null,
      title:
        (s.title as string | undefined) ?? (s.yp_currently_playing as string | undefined) ?? null,
    };
  });
}
